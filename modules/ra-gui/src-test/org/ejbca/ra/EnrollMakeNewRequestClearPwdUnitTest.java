package org.ejbca.ra;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import java.util.Collections;

import org.cesecore.certificates.certificateprofile.CertificateProfile;
import org.cesecore.certificates.certificateprofile.CertificateProfileConstants;
import org.cesecore.certificates.endentity.EndEntityConstants;
import org.ejbca.core.model.ra.raadmin.EndEntityProfile;
import org.ejbca.core.model.ra.raadmin.EndEntityProfileValidationException;
import org.junit.Test;

/**
 * Tests the clear password (batch generation) decision made by the RA web enrollment for profiles with auto-generated passwords.
 */
public class EnrollMakeNewRequestClearPwdUnitTest {

    private static final int CA_ID = 1234;

    private static EndEntityProfile createAutoPasswordProfile(final boolean used, final boolean defaultValue, final boolean required) {
        final EndEntityProfile profile = new EndEntityProfile();
        profile.setUseAutoGeneratedPasswd(true);
        profile.setClearTextPasswordUsed(used);
        profile.setClearTextPasswordDefault(defaultValue);
        profile.setClearTextPasswordRequired(required);
        profile.setAvailableCAs(Collections.singletonList(CA_ID));
        return profile;
    }

    private static void validate(final EndEntityProfile profile, final boolean clearPwd) throws EndEntityProfileValidationException {
        profile.doesUserFulfillEndEntityProfile("username", null, "CN=username", "", "", "",
                CertificateProfileConstants.CERTPROFILE_FIXED_ENDUSER, clearPwd, false, false, EndEntityConstants.TOKEN_USERGEN, CA_ID, null,
                new CertificateProfile(CertificateProfileConstants.CERTPROFILE_FIXED_ENDUSER), null);
    }

    @Test
    public void enforcedTrueIsUsedRegardlessOfUserChoice() throws Exception {
        final EndEntityProfile profile = createAutoPasswordProfile(true, true, true);
        assertTrue(EnrollMakeNewRequestBean.resolveClearPassword(profile, false));
        assertTrue(EnrollMakeNewRequestBean.resolveClearPassword(profile, true));
        // The value now sent to the CA satisfies the profile...
        validate(profile, EnrollMakeNewRequestBean.resolveClearPassword(profile, false));
        // ...whereas the previously hard-coded false was rejected.
        try {
            validate(profile, false);
            fail("Profile enforcing clear password must reject false");
        } catch (EndEntityProfileValidationException e) {
            assertTrue(e.getMessage(), e.getMessage().contains("cannot be false"));
        }
    }

    @Test
    public void enforcedFalseIsUsedRegardlessOfUserChoice() throws Exception {
        final EndEntityProfile profile = createAutoPasswordProfile(true, false, true);
        assertFalse(EnrollMakeNewRequestBean.resolveClearPassword(profile, true));
        assertFalse(EnrollMakeNewRequestBean.resolveClearPassword(profile, false));
        validate(profile, EnrollMakeNewRequestBean.resolveClearPassword(profile, true));
    }

    @Test
    public void notEnforcedHonoursUserChoice() throws Exception {
        for (final boolean defaultValue : new boolean[] { true, false }) {
            final EndEntityProfile profile = createAutoPasswordProfile(true, defaultValue, false);
            for (final boolean choice : new boolean[] { true, false }) {
                assertEquals(choice, EnrollMakeNewRequestBean.resolveClearPassword(profile, choice));
                validate(profile, EnrollMakeNewRequestBean.resolveClearPassword(profile, choice));
            }
        }
    }

    @Test
    public void notUsedAlwaysFalse() throws Exception {
        final EndEntityProfile profile = createAutoPasswordProfile(false, true, false);
        assertFalse(EnrollMakeNewRequestBean.resolveClearPassword(profile, true));
        validate(profile, EnrollMakeNewRequestBean.resolveClearPassword(profile, true));
    }
}
